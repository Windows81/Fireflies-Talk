import { useEffect, type RefObject } from "react";
import type { View } from "react-native";

/** A move this far past the press point turns a click into a window drag. */
const DRAG_THRESHOLD_PX = 4;

/**
 * Lets a frameless window be dragged by grabbing anywhere on it, including its
 * buttons. Native drag regions cannot do this: a control has to opt out of the
 * drag region to be clickable, which leaves nothing to grab. Instead the press
 * is watched here — past the threshold it becomes a window drag and the click
 * that would follow is swallowed.
 */
export function useFloatingWindowDrag(
  ref: RefObject<View | null>,
  handlers: { onStart: () => void; onEnd: () => void },
  enabled = true,
): void {
  useEffect(() => {
    if (!enabled) return;
    // RN Web forwards the View ref to its DOM element.
    const node = ref.current as unknown as HTMLElement | null;
    if (!node) return;

    let start: { x: number; y: number } | null = null;
    let dragging = false;
    let suppressClicksUntil = 0;

    const onPointerDown = (event: PointerEvent) => {
      if (event.button !== 0) return;
      // Screen coordinates, not client: the window follows the cursor during a
      // drag, so window-relative coordinates barely change and would never
      // cross the threshold.
      start = { x: event.screenX, y: event.screenY };
      dragging = false;
    };
    const onPointerMove = (event: PointerEvent) => {
      if (!start || dragging) return;
      if (
        Math.abs(event.screenX - start.x) >= DRAG_THRESHOLD_PX ||
        Math.abs(event.screenY - start.y) >= DRAG_THRESHOLD_PX
      ) {
        dragging = true;
        handlers.onStart();
      }
    };
    const onPointerUp = () => {
      if (dragging) {
        handlers.onEnd();
        // The click generated by this release must not reach the control under
        // the cursor. A short window covers it even if the click arrives late
        // or never — a stale flag would otherwise eat the next real click.
        suppressClicksUntil = Date.now() + 300;
      }
      dragging = false;
      start = null;
    };
    const onClickCapture = (event: MouseEvent) => {
      if (Date.now() > suppressClicksUntil) return;
      suppressClicksUntil = 0;
      event.stopPropagation();
      event.preventDefault();
    };

    node.addEventListener("pointerdown", onPointerDown);
    window.addEventListener("pointermove", onPointerMove);
    window.addEventListener("pointerup", onPointerUp);
    // A cancelled gesture (OS drag, focus loss) never sends pointerup, which
    // would leave the main process following the cursor forever.
    window.addEventListener("pointercancel", onPointerUp);
    window.addEventListener("blur", onPointerUp);
    node.addEventListener("click", onClickCapture, true);
    return () => {
      node.removeEventListener("pointerdown", onPointerDown);
      window.removeEventListener("pointermove", onPointerMove);
      window.removeEventListener("pointerup", onPointerUp);
      window.removeEventListener("pointercancel", onPointerUp);
      window.removeEventListener("blur", onPointerUp);
      node.removeEventListener("click", onClickCapture, true);
      // Unmounting mid-drag must not strand the follow loop either.
      if (dragging) handlers.onEnd();
    };
  }, [ref, handlers, enabled]);
}
