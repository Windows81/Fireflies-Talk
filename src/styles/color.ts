// Returns a color as an rgba() string with the given alpha. Accepts the two
// formats used across the theme: 6-digit hex and rgb()/rgba(). Lets an animated
// background fade by opacity alone, so its RGB never blends toward black at
// intermediate frames.
export const withAlpha = (color: string, alpha: number): string => {
  // Already rgb()/rgba(): keep the channels and override the alpha.
  if (color.startsWith("rgb")) {
    const [r = "0", g = "0", b = "0"] = color.match(/[\d.]+/g) ?? [];
    return `rgba(${r}, ${g}, ${b}, ${alpha})`;
  }
  const hex = color.replace("#", "");
  const r = parseInt(hex.slice(0, 2), 16);
  const g = parseInt(hex.slice(2, 4), 16);
  const b = parseInt(hex.slice(4, 6), 16);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
};

